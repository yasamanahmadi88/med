    PRODUCT_KEY BIGINT NOT NULL,
    PRODUCT_NAME VARCHAR(3) NOT NULL,
    PRODUCT_DESC VARCHAR(300) NOT NULL,
    PRIMARY KEY (PRODUCT_KEY)
);
ALTER TABLE "MEDIATION.tbl_products" ADD CONSTRAINT UK_MED_PRODUCTS_NAME UNIQUE (PRODUCT_NAME);

CREATE TABLE "MEDIATION.TBL_FLOWS" (
    FLOW_KEY BIGINT NOT NULL,
    FLOW_NAME VARCHAR(6) NOT NULL,
    FLOW_DESC VARCHAR(300) NOT NULL,
    FLOW CLOB NOT NULL,
    PRODUCT_NAME VARCHAR(3) NOT NULL,
    PRIMARY KEY (FLOW_KEY)
);
ALTER TABLE "MEDIATION.TBL_FLOWS" ADD CONSTRAINT FK_MED_FLOWS_PRODUCT
    FOREIGN KEY (PRODUCT_NAME) REFERENCES "MEDIATION.tbl_products" (PRODUCT_NAME);

CREATE TABLE "MEDIATION.tbl_modules" (
    MODULE_KEY BIGINT NOT NULL,
    MODULE_NAME VARCHAR(50) NOT NULL,
    DEFAULT_PORT VARCHAR(4) NOT NULL,
    REDIS_KEY_PREFIX VARCHAR(5) NOT NULL,
    STATUS BIGINT NOT NULL,
    LOGGING_MODE VARCHAR(255) NOT NULL,
    LOGGING_FILTER VARCHAR(500),
    DNS_NAME VARCHAR(100) NOT NULL,
    PRIMARY KEY (MODULE_KEY)
);
ALTER TABLE "MEDIATION.tbl_modules" ADD CONSTRAINT UK_MED_MODULES_NAME UNIQUE (MODULE_NAME);

CREATE TABLE "MEDIATION.tbl_configs" (
    CONFIG_KEY BIGINT NOT NULL,
    PROPERTY VARCHAR(100) NOT NULL,
    P_VALUE VARCHAR(300) NOT NULL,
    COMMENT_DESC VARCHAR(200),
    MODULE_NAME VARCHAR(50) NOT NULL,
    PRIMARY KEY (CONFIG_KEY)
);
ALTER TABLE "MEDIATION.tbl_configs" ADD CONSTRAINT FK_MED_CONFIGS_MODULE
    FOREIGN KEY (MODULE_NAME) REFERENCES "MEDIATION.tbl_modules" (MODULE_NAME);

CREATE TABLE "MEDIATION.TBL_INSTANCES" (
    INSTANCE_KEY BIGINT NOT NULL,
