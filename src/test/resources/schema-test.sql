-- Mediation domain tables.
-- Entities use @Table(name = "MEDIATION.TBL_...") so Hibernate validates a *literal*
-- table name that includes the dot (not schema MEDIATION + table TBL_...).
-- H2 therefore needs quoted identifiers matching those names (and lowercase variants).

DROP TABLE IF EXISTS "MEDIATION.TBL_FLOWS";
DROP TABLE IF EXISTS "MEDIATION.TBL_CONFIGS";
DROP TABLE IF EXISTS "MEDIATION.tbl_configs";
DROP TABLE IF EXISTS "MEDIATION.TBL_MODULES";
DROP TABLE IF EXISTS "MEDIATION.tbl_modules";
DROP TABLE IF EXISTS "MEDIATION.TBL_PRODUCTS";
DROP TABLE IF EXISTS "MEDIATION.tbl_products";
DROP TABLE IF EXISTS "MEDIATION.TBL_INSTANCES";
DROP TABLE IF EXISTS "MEDIATION.TBL_VERSIONS";
DROP TABLE IF EXISTS "MEDIATION.tbl_versions";
DROP TABLE IF EXISTS "MEDIATION.TBL_LOGS";
DROP TABLE IF EXISTS "MEDIATION.tbl_logs";

DROP SEQUENCE IF EXISTS "MEDIATION.FLOWS_SEQ";
DROP SEQUENCE IF EXISTS "MEDIATION.PRODUCTS_SEQ";
DROP SEQUENCE IF EXISTS MODULES_SEQ;
DROP SEQUENCE IF EXISTS CONFIGS_SEQ;
DROP SEQUENCE IF EXISTS LOG_SEQ;
DROP SEQUENCE IF EXISTS "sequenceGenerator";
DROP SEQUENCE IF EXISTS SEQUENCEGENERATOR;

CREATE SEQUENCE "MEDIATION.FLOWS_SEQ" START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE "MEDIATION.PRODUCTS_SEQ" START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE MODULES_SEQ START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE CONFIGS_SEQ START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE LOG_SEQ START WITH 1000 INCREMENT BY 1;
CREATE SEQUENCE "sequenceGenerator" START WITH 1000 INCREMENT BY 50;
CREATE SEQUENCE SEQUENCEGENERATOR START WITH 1000 INCREMENT BY 50;

